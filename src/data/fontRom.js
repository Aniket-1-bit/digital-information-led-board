// Convert a string into an array of column byte vectors (each 8 bits high)
export function stringToColumnMatrix(text) {
  const columns = [];
  // Lead-in padding space
  for (let i = 0; i < 8; i++) columns.push(0x00);

  for (let c = 0; c < text.length; c++) {
    const char = text[c];
    const pattern = ASCII_FONT_ROM[char] || ASCII_FONT_ROM['?'] || [0x00, 0x00, 0x00, 0x00, 0x00];
    for (let col = 0; col < pattern.length; col++) {
      columns.push(pattern[col]);
    }
    // Inter-character 1-pixel gap
    columns.push(0x00);
  }

  // Trailing space
  for (let i = 0; i < 16; i++) columns.push(0x00);
  return columns;
}

